// The dashboard styles were drawn right-to-left first. Rather than duplicate
// every ornament by hand, this mirrors the physical bits (left/right offsets,
// "to left" gradients, transform origins) into :dir(ltr) overrides.
// Embeds are skipped on purpose: their left/right float is the user's choice.
import fs from 'node:fs';
import path from 'node:path';

const SOURCES = ['30-home.css', '40-tasks.css', '50-home-ornaments.css'];
const swap = (s) => s.replace(/\b(left|right)\b/g, (w) => (w === 'left' ? 'right' : 'left'));

function topLevelRules(css) {
  const rules = [];
  let i = 0;
  while (i < css.length) {
    if (css.startsWith('/*', i)) { i = css.indexOf('*/', i) + 2; continue; }
    const open = css.indexOf('{', i);
    if (open < 0) break;
    const selector = css.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (j < css.length && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
    if (!selector.startsWith('@')) rules.push({ selector, body: css.slice(open + 1, j - 1) });
    i = j;
  }
  return rules;
}

function flipBody(body) {
  const decls = body.split(/;(?![^(]*\))/).map((d) => d.trim()).filter(Boolean);
  const props = new Map(decls.map((d) => { const k = d.indexOf(':'); return [d.slice(0, k).trim(), d.slice(k + 1).trim()]; }));
  const out = [];
  const both = props.has('left') && props.has('right');
  for (const [prop, value] of props) {
    if (prop === 'left' || prop === 'right') {
      const other = prop === 'left' ? 'right' : 'left';
      out.push(`${other}: ${value}`);
      if (!both) out.push(`${prop}: auto`);
    } else if (prop === 'transform-origin' && /\b(left|right)\b/.test(value)) {
      out.push(`${prop}: ${swap(value)}`);
    } else if (/linear-gradient\(to (left|right)/.test(value)) {
      // the shorthand would also reset background-clip (gradient text), so set only the image
      const target = prop === 'background' && /^linear-gradient\([^;]*\)$/.test(value) ? 'background-image' : prop;
      out.push(`${target}: ${value.replace(/linear-gradient\(to (left|right)/g, (_, w) => `linear-gradient(to ${w === 'left' ? 'right' : 'left'}`)}`);
    } else if (/^(-webkit-)?mask(-image)?$/.test(prop) && /linear-gradient\(to (left|right)/.test(value)) {
      out.push(`${prop}: ${swap(value)}`);
    }
  }
  return out;
}

const addDir = (sel) => sel.split(/,(?![^(]*\))/).map((s) => {
  s = s.trim();
  const pe = s.search(/::[a-z-]+$/);
  return pe >= 0 ? `${s.slice(0, pe)}:dir(ltr)${s.slice(pe)}` : `${s}:dir(ltr)`;
}).join(',\n');

export function generateLtr(dir) {
  const chunks = ['/* generated by scripts/gen-ltr.mjs, do not edit */'];
  for (const file of SOURCES) {
    const css = fs.readFileSync(path.join(dir, file), 'utf8');
    for (const { selector, body } of topLevelRules(css)) {
      const flipped = flipBody(body);
      if (flipped.length) chunks.push(`${addDir(selector)} { ${flipped.join('; ')}; }`);
    }
  }
  return chunks.join('\n') + '\n';
}
